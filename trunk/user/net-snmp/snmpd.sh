#!/bin/sh
#
# snmpd start script for Padavan
# Exposes the ARP table (ipNetToMediaTable, 1.3.6.1.2.1.4.22) so an upper-layer
# (iKuai Q3000) "SNMP layer-3 discovery" can read the REAL MAC of hosts behind
# this router.
#
# Config location: /etc/storage is a writable, persistent (MTD) partition on
# Padavan, so we keep snmpd.conf there instead of the read-only /etc_ro squashfs.
# If /etc/storage is not writable we fall back to /tmp (non-persistent).
#
# Manual debug:
#   /usr/bin/snmpd.sh start
#   ps | grep snmpd
#   /usr/sbin/snmpd -c /etc/storage/snmp/snmpd.conf -f -Lo
#   snmpwalk -v2c -c public 127.0.0.1 1.3.6.1.2.1.4.22
#

SNMPD_BIN=/usr/sbin/snmpd
SNMPD_DIR=/etc/storage/snmp
SNMPD_CONF=$SNMPD_DIR/snmpd.conf

start_snmpd() {
	[ -x "$SNMPD_BIN" ] || return 0
	# already running
	[ -n "$(pidof snmpd)" ] && return 0

	# pick a writable config dir; prefer persistent storage
	if ! mkdir -p "$SNMPD_DIR" 2>/dev/null ; then
		SNMPD_DIR=/tmp/snmp
		SNMPD_CONF=$SNMPD_DIR/snmpd.conf
		mkdir -p "$SNMPD_DIR" 2>/dev/null
	fi

	# (re)generate the minimal read-only config
	cat > "$SNMPD_CONF" 2>/dev/null <<'EOF'
# net-snmp minimal read-only config (auto-generated by snmpd.sh)
rocommunity  public default
view         all    included   .1
syslocation  Router
syscontact   admin@localhost
agentaddress udp:161
EOF

	# start the daemon in the background
	"$SNMPD_BIN" -c "$SNMPD_CONF" -Lo >/dev/null 2>&1 &

	logger -t "snmpd" "started (config: $SNMPD_CONF)"
}

stop_snmpd() {
	[ -z "$(pidof snmpd)" ] && return 0
	killall snmpd 2>/dev/null
	logger -t "snmpd" "stopped"
}

case "$1" in
	start)   start_snmpd ;;
	stop)    stop_snmpd ;;
	restart) stop_snmpd; sleep 1; start_snmpd ;;
	*)       echo "usage: $0 {start|stop|restart}"; exit 1 ;;
esac

exit 0